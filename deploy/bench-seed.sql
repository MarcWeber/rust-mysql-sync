-- Benchmark-Datensatz: db_bench.big mit 100.000 Zeilen.
-- Nur Quelle noetig: `mysql-sync --benchmark` misst ausschliesslich lokal.
--
--   mysql -h 127.0.0.1 -P 7012 -uroot -p < deploy/bench-seed.sql
--   mysql-sync -C config-client.json --benchmark db_bench.big

CREATE DATABASE IF NOT EXISTS db_bench CHARACTER SET utf8mb4;
DROP TABLE IF EXISTS db_bench.big;
CREATE TABLE db_bench.big (
  id INT NOT NULL AUTO_INCREMENT,
  a VARCHAR(64) NOT NULL,
  b INT NOT NULL,
  c DATETIME NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO db_bench.big (a, b, c)
SELECT CONCAT('row-', n, '-', MD5(n)), n % 1000,
       DATE_ADD('2024-01-01', INTERVAL n SECOND)
FROM (
  SELECT d0.N + d1.N * 10 + d2.N * 100 + d3.N * 1000 + d4.N * 10000 + 1 AS n
  FROM (SELECT 0 AS N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
        UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) d0,
       (SELECT 0 AS N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
        UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) d1,
       (SELECT 0 AS N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
        UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) d2,
       (SELECT 0 AS N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
        UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) d3,
       (SELECT 0 AS N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
        UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) d4
) s
WHERE n <= 100000;
